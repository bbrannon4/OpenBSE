#!/usr/bin/env python3
"""Write the SI copy of each I-P standards table.

Usage: python3 tools/standards/convert_ip_to_si.py data/standards/ashrae_90_1/2025

Reads every `ip/table_*.yaml` in the edition directory and writes the same
table to `si/` with each dimensional value converted exactly (factors built
from 1 ft = 0.3048 m, 1 Btu_IT = 1055.05585262 J, 1 °F = 5/9 K) and kept to
7 significant figures. The SI file is marked `derivation: converted_from_ip`.

An SI edition rounds its own values, so a printed SI table can differ in the
last digit. When the SI edition is available, replace the converted file with
its printed values and set `derivation: printed`. `cargo test -p
openbse-standards` checks that the two files agree.
"""
import sys
from pathlib import Path

import yaml

FT = 0.3048
BTU = 1055.05585262
U = BTU / 3600 / FT**2 / (5 / 9)
F = BTU / 3600 / FT / (5 / 9)
LPD = 1 / FT**2
FACTORS = {"lpd": LPD, "lpd_per_height": LPD / FT, "u_factor": U, "c_factor": U, "f_factor": F}


def sig7(x):
    return float(f"{x:.7g}")


def convert(node):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k in FACTORS and isinstance(v, (int, float)):
                out[k] = sig7(v * FACTORS[k])
            else:
                out[k] = convert(v)
        return out
    if isinstance(node, list):
        return [convert(v) for v in node]
    return node


class FlowList(list):
    pass


def flow_list(dumper, data):
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)


def flow_lists(node):
    if isinstance(node, dict):
        return {k: flow_lists(v) for k, v in node.items()}
    if isinstance(node, list):
        if all(not isinstance(v, (dict, list)) for v in node):
            return FlowList(node)
        return [flow_lists(v) for v in node]
    return node


def main(edition_dir):
    edition_dir = Path(edition_dir)
    yaml.add_representer(FlowList, flow_list)
    (edition_dir / "si").mkdir(exist_ok=True)
    for src in sorted((edition_dir / "ip").glob("table_*.yaml")):
        table = yaml.safe_load(src.read_text())
        assert table["units"] == "ip" and table["derivation"] == "printed", src
        si = convert(table)
        si["units"] = "si"
        si["derivation"] = "converted_from_ip"
        header = (
            f"# {table['standard']} {table['edition']}, Table {table['table']}, in SI.\n"
            f"# Generated by tools/standards/convert_ip_to_si.py from ip/{src.name}: exact\n"
            "# conversion of the I-P values, 7 significant figures. Do not edit by hand.\n"
        )
        body = yaml.dump(flow_lists(si), sort_keys=False, allow_unicode=True, width=120)
        (edition_dir / "si" / src.name).write_text(header + body)
        print("wrote", edition_dir / "si" / src.name)


if __name__ == "__main__":
    main(sys.argv[1])
